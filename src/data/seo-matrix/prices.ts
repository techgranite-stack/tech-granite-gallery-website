export function getPriceBand(material: MaterialId, stoneSlug?: string): PriceBand {
  if (stoneSlug && STONE_SPECIFIC_PRICES[stoneSlug]) {
    return STONE_SPECIFIC_PRICES[stoneSlug];
  }
  return MATERIAL_PRICES[material] ?? MATERIAL_PRICES.granite;
}

/**
 * Calculates estimated landed cost per sq ft for a given stone/material at a specific destination location.
 * Formula: Landed = (Base Price + Freight + Handling/Loading) * 1.18 (GST)
 */
export function calculateLandedCost(
  priceBand: PriceBand,
  locationId?: LocationId
): {
  minLanded: number;
  maxLanded: number;
  freightEstimate: number;
  unloadingEstimate: number;
  gstRate: number;
  locationName: string;
} {
  const loc = locationId && LOCATIONS[locationId] ? LOCATIONS[locationId] : LOCATIONS.kishangarh;
  const freightMin = loc.freightPerSqftMin ?? 0;
  const freightMax = loc.freightPerSqftMax ?? 0;
  const avgFreight = Math.round((freightMin + freightMax) / 2);
  const unloading = loc.unloadingPerSqft ?? 1.5;
  const gstRate = 0.18;

  const minLanded = Math.round((priceBand.lowPrice + freightMin + unloading) * (1 + gstRate));
  const maxLanded = Math.round((priceBand.highPrice + freightMax + unloading) * (1 + gstRate));

  return {
    minLanded,
    maxLanded,
    freightEstimate: avgFreight,
    unloadingEstimate: unloading,
    gstRate: 18,
    locationName: loc.name,
  };
}
